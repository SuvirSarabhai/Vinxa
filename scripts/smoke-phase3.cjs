require('./register-typescript.cjs')
const assert = require('node:assert/strict')
const { mkdtempSync, mkdirSync, writeFileSync, readFileSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join, resolve } = require('node:path')
const { randomUUID } = require('node:crypto')
const { _electron } = require('playwright-core')
const { MeetingStore } = require('../src/main/db/repository.ts')
const { MeetingAudioSpool } = require('../src/main/audio/spool.ts')
async function main() {
  const profile = mkdtempSync(join(tmpdir(), 'vinxa-phase3-ui-'))
  const artifacts = resolve('release/phase3-ui')
  mkdirSync(artifacts,{recursive:true})
  const report = { passed:false, profile, realSQLite:true, realElectron:true, notes:'Seeded fixture, not a live model response', errors:[] }
  const id = randomUUID()
  const config = {title:'Persistence acceptance fixture',microphoneEnabled:true,systemAudioEnabled:true,microphoneDeviceId:null}
  const store = new MeetingStore(profile)
  store.create(id,config,Date.now()-60000)
  store.saveFinal({id:'first',meetingId:id,source:'system',speakerId:null,text:'We agreed to review the beta.',startMs:1000,endMs:2000,isFinal:true})
  store.saveFinal({id:'second',meetingId:id,source:'mic',speakerId:null,text:'I will run the tests tomorrow.',startMs:3000,endMs:4000,isFinal:true})
  const spool = await MeetingAudioSpool.create(profile,id,config)
  for(const source of ['mic','system']) await spool.append(source,new Uint8Array(3200),{startSample:0})
  store.audio(id,await spool.finalize())
  store.recording(id,'completed',Date.now())
  store.replaceInsights(id,{summary:'The beta will be reviewed.',decisions:[{text:'Review the beta',atMs:1000}],
    actionItems:[{task:'Run tests',owner:'You',due:'tomorrow',status:'pending'}]},'fixture','mock')
  store.close()
  writeFileSync(join(profile,'phase2-hotkeys.json'),JSON.stringify({start:'Ctrl+Alt+7',pause:'Ctrl+Alt+8',stop:'Ctrl+Alt+9'}))
  const env = {...process.env,VINXA_BACKEND:'local',VINXA_SMOKE_USER_DATA:profile,VINXA_SIDECAR_SOURCE:resolve('.'),HF_HUB_OFFLINE:'1'}
  for(const key of ['ELECTRON_RUN_AS_NODE','ELECTRON_RENDERER_URL','VINXA_CAPTURE_TEST']) delete env[key]
  const launch = () => _electron.launch({executablePath:require('electron'),args:[resolve('.')],env,timeout:30000})
  let desktop
  try {
    desktop=await launch()
    let page=await desktop.firstWindow()
    page.on('pageerror',error=>report.errors.push(error.message))
    await page.getByRole('button',{name:'Library',exact:true}).click()
    await page.getByText('1 meetings · 1 pending actions',{exact:true}).waitFor()
    await page.getByRole('button',{name:'Open meeting',exact:true}).click()
    await page.getByRole('textbox',{name:'Saved meeting title'}).fill('Renamed acceptance meeting')
    await page.getByRole('button',{name:'Rename meeting',exact:true}).click()
    await page.getByRole('heading',{name:'Renamed acceptance meeting',exact:true}).waitFor()
    await page.getByRole('textbox',{name:'Remote speaker name'}).fill('Client')
    await page.getByRole('textbox',{name:'Remote speaker name'}).locator('..').locator('..').getByRole('button',{name:'Save name'}).click()
    await page.getByRole('tab',{name:'Actions',exact:true}).click()
    await page.getByRole('checkbox',{name:'Run tests'}).click()
    await page.getByText('1 meetings · 0 pending actions',{exact:true}).waitFor()
    assert.equal(await page.getByRole('checkbox',{name:'Run tests'}).isChecked(),true)
    await page.getByRole('tab',{name:'Transcript',exact:true}).click()
    await page.getByText('Client',{exact:true}).waitFor()
    await page.getByText('I will run the tests tomorrow.',{exact:true}).waitFor()
    await page.screenshot({path:join(artifacts,'saved-transcript.png'),fullPage:true})
    await page.getByRole('tab',{name:'Decisions',exact:true}).click()
    await page.getByText('Review the beta',{exact:false}).waitFor()
    await page.getByRole('button',{name:'Settings',exact:true}).click()
    await page.getByRole('textbox',{name:'Ollama model',exact:true}).fill('missing-acceptance-model')
    await page.getByRole('button',{name:'Save notes settings',exact:true}).click()
    await page.getByText('Notes settings saved.',{exact:true}).waitFor()
    const privacy = await page.evaluate(()=>window.vinxaMeetings.settings())
    assert.equal(privacy.cloudEnabled,false)
    assert.equal(privacy.provider,'ollama')
    await desktop.close(); desktop=undefined
    desktop=await launch(); page=await desktop.firstWindow()
    page.on('pageerror',error=>report.errors.push(error.message))
    await page.getByRole('button',{name:'Library',exact:true}).click()
    await page.getByRole('heading',{name:'Renamed acceptance meeting',exact:true}).waitFor()
    await page.getByRole('button',{name:'Open meeting',exact:true}).click()
    await page.getByText('The beta will be reviewed.',{exact:true}).waitFor()
    const saved = await page.evaluate(id=>window.vinxaMeetings.get(id),id)
    assert.equal(saved.actions[0].status,'done')
    assert.equal(saved.speakers.system,'Client')
    assert.equal(saved.transcript[0].source,'system')
    assert.equal(saved.transcript.length,2)
    for(const wav of [saved.meeting.microphoneAudioPath,saved.meeting.systemAudioPath]) assert.equal(readFileSync(wav).readUInt32LE(40),3200)
    await page.getByRole('button',{name:'Regenerate notes',exact:true}).click()
    await page.getByText(/configured Ollama model is missing|Ollama is unavailable/).waitFor({timeout:15000})
    const unavailable=await page.evaluate(id=>window.vinxaMeetings.get(id),id)
    assert.equal(unavailable.meeting.notesStatus,'completed')
    assert.match(unavailable.meeting.notesMessage,/Previous notes retained/)
    assert.equal(unavailable.insights.summary,saved.insights.summary)
    assert.equal(unavailable.actions[0].status,'done')
    await page.screenshot({path:join(artifacts,'saved-overview.png'),fullPage:true})
    assert.deepEqual(report.errors,[])
    report.passed=true
    report.restart=true
    report.unavailableProviderPreservedNotes=true
    console.log('PASS real Electron Library, title/speaker/action edits, SQLite restart, separate WAVs, pending notes and local settings')
  } catch(error) {report.failure=String(error); throw error}
  finally {await desktop?.close();writeFileSync(join(artifacts,'report.json'),JSON.stringify(report,null,2))}
}
main().catch(error=>{console.error(error);process.exitCode=1})
